/**
 * Builds @newbrush/fonts (specs/001 T091, FR-022): opt-in, self-hostable variable fonts wired to the font.family
 * tokens. Sources are the Fontsource variable packages (OFL-1.1, already subsetted per unicode-range); this copies
 * the weight-axis WOFF2 files, writes @font-face rules with font-display: swap, adds metric-matched local fallbacks
 * (Capsize) so the swap does not shift layout, and overrides --nb-font-family-* with the font first and the
 * system stack after it.
 */
import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { basename, dirname, join } from "node:path";
import { createFontStack, type FontMetrics } from "@capsizecss/core";

const require = createRequire(import.meta.url);
const HEADER =
  "/* @newbrush/fonts: generated by packages/fonts/build.ts, do not edit. Fonts: SIL OFL 1.1 (see licenses/). */\n";

interface Family {
  id: string;
  /** font-family name of the web font (Fontsource's). */
  name: string;
  pkg: string;
  /** Token it fills: --nb-font-family-<token>. */
  token: "sans" | "serif" | "mono";
  metrics: string;
  fallback: string;
}

const FAMILIES: Family[] = [
  {
    id: "inter",
    name: "Inter Variable",
    pkg: "@fontsource-variable/inter",
    token: "sans",
    metrics: "inter",
    fallback: "arial",
  },
  {
    id: "fraunces",
    name: "Fraunces Variable",
    pkg: "@fontsource-variable/fraunces",
    token: "serif",
    metrics: "fraunces",
    fallback: "georgia",
  },
  {
    id: "jetbrains-mono",
    name: "JetBrains Mono Variable",
    pkg: "@fontsource-variable/jetbrains-mono",
    token: "mono",
    metrics: "jetBrainsMono",
    fallback: "courierNew",
  },
];

/** The system stacks newBrush ships today, from the built tokens. */
const tokens = JSON.parse(
  await readFile(require.resolve("@newbrush/tokens/tokens.json"), "utf8"),
) as {
  tokens: { name: string; value: string }[];
};
const systemStack = (token: string) => {
  const value = tokens.tokens.find((t) => t.name === `font.family.${token}`)?.value;
  if (!value) throw new Error(`No font.family.${token} token`);
  return value;
};

const metrics = async (name: string) =>
  ((await import(`@capsizecss/metrics/${name}`)) as { default: FontMetrics }).default;

interface Face {
  file: string;
  style: string;
  weight: string;
  unicodeRange: string;
}

/** @font-face blocks of a Fontsource stylesheet. */
function faces(css: string): Face[] {
  return [...css.matchAll(/@font-face\s*\{([^}]*)\}/g)].map((m) => {
    const body = m[1] ?? "";
    const get = (prop: string) => new RegExp(`${prop}:\\s*([^;]+);`).exec(body)?.[1]?.trim() ?? "";
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)?.[1];
    if (!file) throw new Error(`No WOFF2 source in ${body}`);
    return {
      file,
      style: get("font-style"),
      weight: get("font-weight"),
      unicodeRange: get("unicode-range"),
    };
  });
}

await rm("dist", { recursive: true, force: true });
await mkdir("dist/files", { recursive: true });
await mkdir("dist/licenses", { recursive: true });

const manifest: {
  families: {
    id: string;
    name: string;
    token: string;
    fallback: string;
    weights: string;
    styles: string[];
    files: { file: string; bytes: number }[];
    license: string;
  }[];
} = { families: [] };
const all: string[] = [];

for (const family of FAMILIES) {
  const dir = dirname(require.resolve(`${family.pkg}/package.json`));
  const list = [
    ...faces(await readFile(join(dir, "wght.css"), "utf8")),
    ...faces(await readFile(join(dir, "wght-italic.css"), "utf8")),
  ];
  const files: { file: string; bytes: number }[] = [];
  for (const face of list) {
    await copyFile(join(dir, "files", face.file), join("dist/files", face.file));
    files.push({ file: face.file, bytes: (await readFile(join(dir, "files", face.file))).length });
  }
  await copyFile(join(dir, "LICENSE"), `dist/licenses/${family.id}.txt`);

  const fallback = createFontStack([await metrics(family.metrics), await metrics(family.fallback)]);
  const fallbackName = `${(await metrics(family.metrics)).familyName} Fallback`;
  const fontFaces = list
    .map(
      (f) =>
        `@font-face {\n  font-family: "${family.name}";\n  font-style: ${f.style};\n  font-weight: ${f.weight};\n` +
        `  font-display: swap;\n  src: url("./files/${f.file}") format("woff2");\n  unicode-range: ${f.unicodeRange};\n}`,
    )
    .join("\n\n");
  const stack = `"${family.name}", "${fallbackName}", ${systemStack(family.token)}`;
  const css = [
    `/* ${family.name} → --nb-font-family-${family.token} */`,
    fontFaces,
    "",
    "/* Metric-matched local fallback: the swap to the web font does not shift layout. */",
    fallback.fontFaces.trim(),
    "",
    "/* Doubled :root outranks the framework's token declaration wherever this file is loaded. */",
    "@layer nb.tokens {",
    "  :root:root,",
    "  :root ::backdrop {",
    `    --nb-font-family-${family.token}: ${stack};`,
    "  }",
    "}",
    "",
  ].join("\n");
  await writeFile(`dist/${family.id}.css`, HEADER + css);
  all.push(css);
  manifest.families.push({
    id: family.id,
    name: family.name,
    token: `font.family.${family.token}`,
    fallback: fallbackName,
    weights: list[0]?.weight ?? "",
    styles: [...new Set(list.map((f) => f.style))],
    files,
    license: `licenses/${basename(family.id)}.txt`,
  });
}

await writeFile("dist/fonts.css", HEADER + all.join("\n"));
await writeFile("dist/manifest.json", `${JSON.stringify(manifest, null, 2)}\n`);
const bytes = manifest.families.flatMap((f) => f.files).reduce((n, f) => n + f.bytes, 0);
console.log(
  `fonts: ${manifest.families.length} families, ${manifest.families.flatMap((f) => f.files).length} WOFF2 files (${(bytes / 1024).toFixed(0)} kB on disk; browsers fetch only the unicode ranges a page uses)`,
);
