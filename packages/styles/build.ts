/**
 * Builds @newbrush/styles (specs/004-design-styles T006): every src/<name>/style.json (+ recipes.css, preview.html)
 * becomes dist/<name>.css; dist/styles.css holds all of them followed by the `.style-default` reset, and
 * dist/manifest.json lists them (`Style[]`, merged into newbrush's manifest).
 */
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import {
  checkUnique,
  type LoadedStyle,
  manifestEntry,
  parseStyle,
  resetCss,
  styleCss,
  tokenIndex,
} from "./lib/styles.ts";

const require = createRequire(import.meta.url);
const HEADER = "/* @newbrush/styles: generated by packages/styles/build.ts, do not edit. */\n";

const tokens = tokenIndex(
  JSON.parse(await readFile(require.resolve("@newbrush/tokens/tokens.json"), "utf8")),
  await readFile(require.resolve("@newbrush/tokens/tokens.css"), "utf8"),
);

const optional = async (file: string) => (existsSync(file) ? readFile(file, "utf8") : undefined);
const dirs = (await readdir("src", { withFileTypes: true }))
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();
const styles: LoadedStyle[] = [];
for (const dir of dirs) {
  const source = parseStyle(
    JSON.parse(await readFile(join("src", dir, "style.json"), "utf8")),
    `src/${dir}/style.json`,
  );
  if (source.name !== dir) throw new Error(`src/${dir}/style.json: name must be "${dir}"`);
  styles.push({
    source,
    recipes: await optional(join("src", dir, "recipes.css")),
    preview: await optional(join("src", dir, "preview.html")),
  });
}
checkUnique(styles.map((s) => s.source));

await rm("dist", { recursive: true, force: true });
await mkdir("dist", { recursive: true });
const all: string[] = [];
for (const style of styles) {
  const css = styleCss(style, tokens);
  await writeFile(`dist/${style.source.name}.css`, HEADER + css);
  all.push(css);
}
all.push(resetCss(styles, tokens));
await writeFile("dist/styles.css", HEADER + all.join("\n"));
await writeFile(
  "dist/manifest.json",
  `${JSON.stringify({ styles: styles.map((s) => manifestEntry(s, tokens)) }, null, 2)}\n`,
);
console.log(`styles: ${styles.length} styles (${styles.map((s) => s.source.name).join(", ")})`);
