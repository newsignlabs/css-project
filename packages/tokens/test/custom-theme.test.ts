import { readFile } from "node:fs/promises";
import { beforeAll, describe, expect, it } from "vitest";
import { checkThemeName, customThemeCss, themeDeclarations } from "../lib/custom-theme.ts";
import { generateScale } from "../lib/scale.ts";

/** specs/001 T065: named custom themes for `data-nb-theme="<name>"`. */

let tokensCss: string;
beforeAll(async () => {
  tokensCss = await readFile(new URL("../dist/css/tokens.css", import.meta.url), "utf8");
});

describe("checkThemeName", () => {
  it("accepts lowercase names and rejects built-ins and invalid characters", () => {
    expect(checkThemeName("acme")).toBeNull();
    expect(checkThemeName("acme-dark-2")).toBeNull();
    expect(checkThemeName("dark")).toMatch(/built-in/);
    expect(checkThemeName("Acme")).toMatch(/lowercase/);
    expect(checkThemeName("2fast")).toMatch(/start with a letter/);
    expect(checkThemeName('x"]{}')).not.toBeNull();
  });
});

describe("themeDeclarations", () => {
  it("light: every semantic token with the light scheme marker", () => {
    const light = themeDeclarations(tokensCss, "light");
    expect(light.get("color-scheme")).toBe("light");
    expect(light.get("--nb-scheme")).toBe("light");
    expect(light.get("--nb-color-accent")).toBe("var(--nb-color-brand-600)");
    expect(light.get("--nb-color-surface")).toBe("var(--nb-color-neutral-50)");
    expect(light.has("--nb-color-brand-600")).toBe(false); // palettes are primitives, not theme declarations
  });

  it("dark and contrast: light declarations with that theme's overrides", () => {
    const dark = themeDeclarations(tokensCss, "dark");
    expect(dark.get("color-scheme")).toBe("dark");
    expect(dark.get("--nb-color-accent")).toBe("var(--nb-color-brand-400)");
    expect(dark.get("--nb-color-surface")).toBe("var(--nb-color-neutral-950)");
    const contrast = themeDeclarations(tokensCss, "contrast");
    expect(contrast.get("--nb-contrast")).toBe("more");
    expect(contrast.get("color-scheme")).toBe("light");
    expect(contrast.get("--nb-color-accent")).toBe("var(--nb-color-brand-800)");
    expect(contrast.size).toBe(themeDeclarations(tokensCss, "light").size + 1);
  });

  it("refuses CSS that is not tokens.css", () => {
    expect(() => themeDeclarations(".x { color: red }", "light")).toThrow(/tokens\.css/);
  });
});

describe("customThemeCss", () => {
  it("scopes the seeded palette and the base theme to data-nb-theme with (0,3,0) specificity", () => {
    const css = customThemeCss({
      name: "acme",
      from: "dark",
      seeds: { brand: "#e11d48" },
      tokensCss,
      command: "nb theme create acme",
    });
    const selector = '[data-nb-theme="acme"][data-nb-theme="acme"][data-nb-theme="acme"]';
    expect(css).toMatch(
      /^\/\* newBrush theme "acme": based on dark; seeds: brand #e11d48\.\n \* Generated by: nb theme create acme/,
    );
    expect(css).toContain("@layer nb.tokens {");
    expect(css).toContain(`  ${selector} {\n    color-scheme: dark;`);
    for (const s of generateScale("#e11d48"))
      expect(css).toContain(
        `--nb-color-brand-${s.step}: var(--nb-tint-brand-${s.step}, ${s.value});`,
      );
    expect(css).toContain("--nb-color-accent: var(--nb-color-brand-400);");
    expect(css).not.toContain("--nb-color-neutral-50:"); // unseeded palettes are inherited
    expect(css.match(/:root/g)).toBeNull();
  });

  it("is deterministic and rejects bad names and seeds", () => {
    const a = customThemeCss({ name: "x", seeds: { brand: "red" }, tokensCss });
    expect(customThemeCss({ name: "x", seeds: { brand: "red" }, tokensCss })).toBe(a);
    expect(() => customThemeCss({ name: "contrast", tokensCss })).toThrow(/built-in/);
    expect(() => customThemeCss({ name: "x", seeds: { brand: "nope" }, tokensCss })).toThrow(
      /theme\.seeds\.brand/,
    );
  });
});
