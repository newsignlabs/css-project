/**
 * Named custom themes (specs/001 T065, US3 acceptance scenario 4): `data-nb-theme="<name>"` on any element applies
 * the theme to that subtree. A theme is a built-in base (light, dark or contrast) plus palettes generated from
 * seeds. Its semantic declarations are read from the built tokens.css, so a custom theme can never drift from the
 * framework's own themes.
 */

import { checkSeeds, palettes, type SeedName, type Seeds, tintableCss } from "./seeds.ts";
import { THEME_NAMES, type ThemeName } from "./themes.ts";

export interface CustomThemeOptions {
  /** Theme name, used as `data-nb-theme="<name>"`. */
  name: string;
  /** Built-in theme to start from (default "light"). */
  from?: ThemeName;
  seeds?: Seeds;
  /** Contents of @newbrush/tokens/tokens.css. */
  tokensCss: string;
  /** The command that generated the file, recorded in its header. */
  command?: string;
}

const NAME = /^[a-z][a-z0-9-]*$/;

/** Validates a custom theme name; returns a problem or null. */
export function checkThemeName(name: string): string | null {
  if (!NAME.test(name))
    return `theme name "${name}" must start with a letter and use only lowercase letters, digits and hyphens`;
  if ((THEME_NAMES as readonly string[]).includes(name))
    return `"${name}" is a built-in theme; choose another name`;
  return null;
}

/** Top-level rules of the nb.tokens layer in tokens.css, keyed by their (whitespace-normalised) selector. */
function rules(tokensCss: string): Map<string, string[]> {
  const out = new Map<string, string[]>();
  for (const m of tokensCss.matchAll(/^ {2}(?! )([^@}\s][^{}]*?) \{\n([\s\S]*?)\n {2}\}/gm)) {
    const selector = (m[1] ?? "").replace(/\s+/g, " ").trim();
    const decls = (m[2] ?? "")
      .split("\n")
      .map((l) => l.trim())
      .filter(Boolean);
    if (!out.has(selector)) out.set(selector, decls);
  }
  return out;
}

const BASE_SELECTORS: Record<ThemeName, string> = {
  light: ':root, ::backdrop, [data-nb-theme="light"], [data-nb-theme="contrast"]',
  dark: '[data-nb-theme="dark"]',
  contrast: '[data-nb-theme="contrast"]',
};

/** Declarations of a built-in theme as `property → value`, in source order: light, then the theme's overrides. */
export function themeDeclarations(tokensCss: string, from: ThemeName): Map<string, string> {
  const found = rules(tokensCss);
  const light = found.get(BASE_SELECTORS.light);
  if (!light)
    throw new Error("tokens.css has no light theme block; pass @newbrush/tokens/tokens.css");
  const layers = from === "light" ? [light] : [light, found.get(BASE_SELECTORS[from]) ?? []];
  const decls = new Map<string, string>();
  for (const list of layers)
    for (const line of list) {
      const i = line.indexOf(":");
      if (i > 0)
        decls.set(
          line.slice(0, i).trim(),
          line
            .slice(i + 1)
            .replace(/;$/, "")
            .trim(),
        );
    }
  return decls;
}

/**
 * CSS for a named theme. Selectors repeat the attribute three times: specificity (0,3,0) outranks the framework's
 * theme rules and `theme.seeds` overrides (both (0,2,0) at most), so the theme wins inside its subtree whatever the
 * stylesheet order. Palettes keep the `var(--nb-tint-…)` form, so a runtime `--nb-color-<palette>-seed` still works.
 */
export function customThemeCss({
  name,
  from = "light",
  seeds = {},
  tokensCss,
  command,
}: CustomThemeOptions): string {
  const problem = checkThemeName(name) ?? checkSeeds(seeds)[0];
  if (problem) throw new Error(problem);
  const selector = `[data-nb-theme="${name}"]`.repeat(3);
  const decls = [...themeDeclarations(tokensCss, from)].map(([p, v]) => `    ${p}: ${v};`);
  const generated = palettes(seeds) as Partial<
    Record<SeedName, ReturnType<typeof palettes>[string]>
  >;
  const palette = tintableCss(generated, [selector], { tints: false, p3: "differing" });
  const seedList = Object.entries(seeds)
    .map(([k, v]) => `${k} ${v}`)
    .join(", ");
  return [
    `/* newBrush theme "${name}": based on ${from}${seedList ? `; seeds: ${seedList}` : ""}.`,
    ...(command ? [` * Generated by: ${command}`] : []),
    ` * Load it after newbrush.css, then set data-nb-theme="${name}" on <html> or any element.`,
    " * Regenerate with the command rather than editing by hand. */",
    "@layer nb.tokens {",
    ...(palette ? [palette, ""] : []),
    `  ${selector} {`,
    ...decls,
    "  }",
    "}",
    "",
  ].join("\n");
}
